#!/usr/bin/env python3
# Write the dlregsym() table that exports every global symbol defined in the
# given static libraries to DXE3 modules loaded by pumpkin.exe:
#
#   dxeexport.py [-o table.c] [-n name] [--nm NM] lib.a ...
#
# The table self-registers (DXE_EXPORT_TABLE_AUTO) and each entry references
# the symbol, so linking the file into the host pulls the whole library in and
# a module may import any of it. Symbol names are taken as nm prints them
# (COFF, with the leading underscore), which is the form the DXE loader and
# extern_asm() expect.

import argparse
import re
import subprocess
import sys

NAME = re.compile(r'^_[A-Za-z_][A-Za-z0-9_]*$')
CLASSES = set('TDBRC')   # code, data, bss, read-only data, common


def defined(nm, lib):
    out = subprocess.run([nm, '--defined-only', '-g', lib], check=True,
                         capture_output=True, text=True).stdout
    names = set()
    for line in out.splitlines():
        f = line.split()
        if len(f) == 3 and f[1] in CLASSES and NAME.match(f[2]):
            names.add(f[2])
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('-o', dest='output')
    ap.add_argument('-n', dest='name', default='dxe_export_table')
    ap.add_argument('--nm', default='i686-pc-msdosdjgpp-nm')
    ap.add_argument('libs', nargs='+')
    args = ap.parse_args()

    names = sorted(set().union(*(defined(args.nm, l) for l in args.libs)))
    out = open(args.output, 'w') if args.output else sys.stdout
    out.write('/* Generated by dxeexport.py from %s: every global symbol of these\n'
              '   libraries, exported to DXE3 modules through dlregsym(). Do not edit. */\n'
              '#include <sys/dxe.h>\n\n' % ' '.join(args.libs))
    for n in names:
        out.write('extern_asm(%s);\n' % n)
    out.write('\nDXE_EXPORT_TABLE_AUTO (%s)\n' % args.name)
    for n in names:
        out.write('  DXE_EXPORT_ASM (%s)\n' % n)
    out.write('DXE_EXPORT_END\n')


if __name__ == '__main__':
    main()
